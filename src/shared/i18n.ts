export const dict: Record<Locale, Record<TKey, string>> = { en, vi };

/** Translate a key; `{name}` placeholders are replaced from vars. Falls back to en, then to the key. */
export function t(locale: Locale, key: TKey, vars?: Record<string, string | number>): string {
  const s = dict[locale]?.[key] ?? en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : match,
  );
}
